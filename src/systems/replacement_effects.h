class Orderer;

// Replacement-effect dispatcher (MTG Comprehensive Rules 614 / 616).
//
// A replacement effect (614) is a kind of continuous effect that watches a
// particular event and replaces it with a different event ("shields"). Unlike the
// 613 layer system (which timestamp-orders static abilities), replacement effects
// are not ordered: when more than one would modify the same event, the affected
// object's controller/owner chooses ONE to apply, then the process repeats with the
// remaining applicable effects (616.1 / 616.1f). A replacement effect gets only one
// opportunity per event (614.5).
//
// A ReplacementEvent is a small mutable description of an event that is *about to*
// happen. The caller fills in the input fields, calls dispatch(), then carries out
// the (possibly modified) outcome fields. Replacement effects may be generated by a
// static ability, a keyword (e.g. dredge), or a resolving spell/ability — the
// dispatcher does not care about the source, only the event.
struct ReplacementEvent {
    enum Type {
        ENTERS_BATTLEFIELD,  // a permanent is about to enter the battlefield
        MOVE_TO_ZONE,        // a card is about to change zones
        UNTAP,               // a permanent is about to untap during its controller's untap step
        PRODUCE_MANA,        // a permanent is about to produce mana from being tapped (Damping Sphere)
        COUNTER,             // an object on the stack is about to be countered
    };

    Type type;
    Entity entity = 0;                                 // affected object
    Zone::Ownership affected_player = Zone::PLAYER_A;   // 616.1 chooser

    // ENTERS_BATTLEFIELD in/out. `ask_inline`: a choice the entry needs (pay life to enter
    // untapped) is asked on the spot rather than parked for the state-based pass to re-run —
    // set for a token, which enters in the middle of the effect that creates it.
    bool ask_inline = false;
    bool enters_tapped = false;
    int  etb_p1p1 = 0;                                 // counters to add when the permanent enters (614.1c); count of etb_counter_type
    std::string etb_counter_type = "P1P1";             // kind of "enters with" counter ("P1P1", "CHARGE", ...)

    // COUNTER: `entity` is the object, `affected_player` its controller; `prevented` the outcome.

    // MOVE_TO_ZONE in/out
    Zone::ZoneValue destination = Zone::GRAVEYARD;     // caller seeds the natural destination; dispatch may redirect
    Zone::ZoneValue origin = Zone::LIBRARY;            // caller seeds the zone the card is leaving
    bool prevented = false;                            // 614.13/CantHappen — the event doesn't happen: a move leaves the card in its origin zone (Grafdigger's Cage), a counter leaves the spell on the stack (Hexing Squelcher)
    bool with_void_counter = false;                    // out: the card is exiled with a void counter (Dauthi Voidwalker); the caller records it on the new object
    // DISCARD_ELSE_GRAVEYARD additional cost (Mox Diamond / Chrome Mox): the card the affected
    // player chose to discard as this permanent enters. dispatch() has no orderer, so the caller
    // (Orderer::add_to_zone) performs the discard when this is non-zero (destination stays
    // battlefield). When the player declines/can't pay, dispatch redirects `destination` to the
    // graveyard and leaves this 0.
    Entity pending_discard = 0;

    // UNTAP outcome (Choke, 614.1d)
    bool   skip_untap = false;                         // a replacement prevents this permanent from untapping

    // PRODUCE_MANA in/out (Damping Sphere, 614.1). Caller seeds the producing permanent (entity),
    // its controller (affected_player), the color it would produce and how much. dispatch() may
    // rewrite produced_color (e.g. to {C}) and sets mana_replaced; the caller adds produced_amount
    // mana of the (possibly replaced) color to the pool.
    bool   simulation = false;                         // input: a mana simulation (can_pay_mana), not a real event: --coverage does not count it
    Colors produced_color = COLORLESS;                 // input: color the source would produce; dispatch may replace it
    size_t produced_amount = 0;                        // input: amount of mana produced this tap
    bool   mana_replaced = false;                      // output: a ProduceMana replacement rewrote the production (idempotency guard)
};

namespace replacement {
// Apply every applicable replacement effect to `ev` per rules 614/616, mutating its
// outcome fields in place. Prompts the affected player to choose one at a time when
// more than one applies (616.1).
void dispatch(ReplacementEvent &ev);

// What one row of a draw's replacement menu does: draw normally, dredge, or what a replacement's
// ReplaceWith$ says instead.
struct DrawReplacementOption {
    Entity source = 0;  // the dredge card, or what generates the replacement (0: an effect object's)
    int mill = 0;       // its dredge number (cards to mill); 0 for the other rows
    const AbilityDef *body = nullptr;            // ReplaceWith$ of a replacement that isn't a dredge
    Zone::Ownership controller = Zone::UNKNOWN;  // its controller, who the body acts for
};

// The menu of one draw by `player` (CR 616.1), each row `(*opts)[i]`: a replacement that must apply
// if it can, then each dredge (CR 702.52a), and a first row "Draw a card" while nothing makes the
// player do otherwise, so the default (index 0) keeps the draw. Empty when nothing applies, the
// promptless common case; one row when a single replacement must apply, which needs no question.
// Pure ECS reads, so a suspended prompt re-derives the identical menu on resume. Shared by the
// turn-based draw batch (resume_pending_draws) and the suspendable resolution-time draw loop
// (effects::draw_n_with_replacements).
std::vector<LegalAction> collect_draw_replacements(Zone::Ownership player,
                                                   std::vector<DrawReplacementOption> *opts);

// Carries out row `option` of a draw by `player` that needs no ReplaceWith$ run: the draw or a
// dredge. A row with a body leaves it on `batch` for the draw loop to run where it may suspend
// (draw_body); either way the card is accounted for when it returns, or when the body completes.
void take_draw_option(Orderer &orderer, Zone::Ownership player, const DrawReplacementOption &option, DrawBatch &batch);

// The ability `batch`'s ReplaceWith$ body runs as (CR 614.6), an ability of what generated the
// replacement, controlled by that replacement's controller, nothing resolving.
Ability draw_body(const DrawBatch &batch);

// Additive draw replacement (CR 614.1, Quantum Riddler): the number of EXTRA cards `player` draws
// for a "would draw one or more cards" event, summed over every DRAW_ADD replacement on `player`'s
// battlefield permanents whose CheckSVar condition currently holds ("as long as you have one or
// fewer cards in hand"). 0 = no additive replacement applies (the common case). A pure ECS read
// (battlefield scan + SVar evaluation) with no prompt, evaluated once as the event starts, so the
// condition sees the pre-draw hand. Every card of the event, the extra ones too, is then a draw of
// its own (CR 121.2), with its own replacement effects.
int draw_count_bonus(Zone::Ownership player);

// Diagnostics: how many 616.1 choose-one-of-several-replacements prompts this
// process has emitted. The choose_one prompt is the one remaining blocking
// mid-flow prompt family (see the residual note at choose_one in
// replacement_effects.cpp); this counter quantifies its reachability in any
// measurement run.
size_t choose_one_prompt_count();
}

